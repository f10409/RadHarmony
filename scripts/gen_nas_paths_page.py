#!/usr/bin/env python
"""Build ``docs/internal/nas_paths.md`` from ``configs/data_paths.json``.

    python scripts/gen_nas_paths_page.py            # write the page
    python scripts/gen_nas_paths_page.py --check    # exit 1 if the page is out of date

Do not edit the page by hand. Edit the config, then run this script.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dataset_paths import CONFIG_PATH, load  # noqa: E402

# Outside docs/wiki, so the page is never part of a published site.
PAGE = Path(__file__).resolve().parents[1] / "docs" / "internal" / "nas_paths.md"

STATUS_TEXT = {
    "ok": "ok",
    "restricted": "restricted (not readable by all users)",
    "not_on_nas": "not on the NAS",
    "alias": "generic class",
}


def _rows(paths: dict[str, str], variant: str = "") -> list[str]:
    tag = f" (variant `{variant}`)" if variant else ""
    return [f"| `{arg}`{tag} | `{p}` |" for arg, p in paths.items()]


def render(datasets: dict) -> str:
    """Return the page text for the ``datasets`` mapping of the config."""
    out = [
        "# NAS Dataset Paths",
        "",
        "<!-- Generated by scripts/gen_nas_paths_page.py from configs/data_paths.json. Do not edit. -->",
        "",
        "!!! warning \"Internal page\"",
        "    These are the NAS paths of our lab, including internal data. Do not copy this page "
        "to the public repo.",
        "",
        "This page lists the NAS paths for each registry key. Pass the paths to the dataset class "
        "as keyword arguments. In code, read them with `scripts/dataset_paths.py`. Run this "
        "example from the repo root:",
        "",
        "<!-- block: cwd=repo -->",
        "```python",
        "import sys",
        'sys.path.insert(0, "scripts")',
        "from dataset_paths import paths",
        "from radharmony.dataset import CTRATEDataset, VinDrCXRTrainDataset",
        "",
        'ds = VinDrCXRTrainDataset(**paths("vindr_cxr_train"), output_cls=True)',
        "# A variant is a second data folder for the same class:",
        'valid_ds = CTRATEDataset(**paths("ct_rate", "valid"), output_cls=True)',
        "```",
        "",
    ]
    for key, e in datasets.items():
        out += [f"## `{key}`", "", f"Status: {STATUS_TEXT[e['status']]}."]
        if e.get("verified"):
            out[-1] += f" Paths checked on {e['verified']}."
        out.append("")
        if e.get("use"):
            out += ["Use one of these keys: " + ", ".join(f"`{u}`" for u in e["use"]) + ".", ""]
        rows = _rows(e.get("paths", {}))
        for name, p in e.get("variants", {}).items():
            rows += _rows(p, name)
        if rows:
            out += ["| Argument | Path |", "|---|---|", *rows, ""]
        if e.get("env"):
            out += ["Environment overrides: "
                    + ", ".join(f"`{var}` sets `{arg}`" for arg, var in e["env"].items()) + ".", ""]
        if e.get("note"):
            out += [e["note"], ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    args = p.parse_args(argv)

    text = render(load(CONFIG_PATH))
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != text:
            print(f"{PAGE} is out of date. Run: python scripts/gen_nas_paths_page.py")
            return 1
        return 0
    PAGE.write_text(text)
    print(f"Wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
